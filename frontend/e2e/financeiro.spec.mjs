import { test, expect } from '@playwright/test'

test('cadastrar contas, cartões, entradas e gerenciar gastos', async ({ page }, testInfo) => {
  const numero = Date.now().toString().slice(-11)
  const email = `financeiro${numero}@e2e.example.com`
  const senha = 'Senha-de-teste-123'
  const cadastro = await page.request.post('/api/cadastro', { data: {
    nome: 'Pessoa Financeiro', cpf: numero, telefone: numero, email, senha,
  } })
  expect(cadastro.status()).toBe(201)
  await page.goto('/login')
  await page.getByLabel('E-mail').fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(senha)
  await page.getByRole('button', { name: 'Entrar na conta' }).click()
  const area = page.getByRole('region', { name: 'Cadastros financeiros' })
  const salvar = () => area.getByRole('button', { name: 'Salvar cadastro', exact: true }).click()
  const aba = async nome => {
    await area.getByRole('button', { name: nome, exact: true }).click()
    await expect(area.getByRole('heading', { name: nome, exact: true })).toBeVisible()
  }
  await aba('Contas bancárias')
  await page.getByLabel('Banco', { exact: true }).fill('Banco Teste')
  await page.getByLabel('Agência', { exact: true }).fill('0001')
  await page.getByLabel('Número da conta').fill('0012-3')
  await salvar()
  await expect(area.locator('li')).toContainText('Agência 0001 · Conta 0012-3')
  // A mesma agência e número não podem ser cadastrados novamente.
  await page.getByLabel('Banco', { exact: true }).fill('Banco Teste')
  await page.getByLabel('Agência', { exact: true }).fill('0001')
  await page.getByLabel('Número da conta').fill('0012-3')
  await salvar()
  await expect(area.getByRole('alert')).toContainText('Já existe uma conta')

  await aba('Cartões')
  await page.getByLabel('Nome do cartão').fill('Meu cartão')
  await page.getByLabel('Dia de fechamento').fill('31')
  await page.getByLabel('Conta bancária (opcional)').selectOption({ label: 'Banco Teste · 0001 / 0012-3' })
  await salvar()
  await expect(area.locator('li')).toContainText('Fechamento: dia 31')
  await page.getByLabel('Nome do cartão').fill('Cartão sem conta')
  await page.getByLabel('Dia de fechamento').fill('1')
  await salvar()
  await expect(area.locator('li').filter({ hasText: 'Cartão sem conta' })).toContainText('Sem conta')

  await aba('Entradas')
  await page.getByLabel('Descrição', { exact: true }).fill('Salário')
  await page.getByLabel('Valor (R$)').fill('1500.50')
  await page.getByLabel('Data do lançamento').fill('2026-10-31')
  await page.getByLabel('Conta bancária (opcional)').selectOption({ label: 'Banco Teste · 0001 / 0012-3' })
  await salvar()
  await expect(area.locator('li')).toContainText('Salário')
  await expect(area.locator('li')).toContainText('Banco Teste')

  await aba('Gastos')
  await page.getByLabel('Descrição', { exact: true }).fill('Mercado')
  await page.getByLabel('Valor (R$)').fill('120.90')
  await page.getByLabel('Data do lançamento').fill('2026-10-31')
  await page.getByLabel('Categoria').fill('Alimentação')
  await page.getByLabel('Vencimento (opcional)').fill('2026-11-05')
  await page.getByLabel('Cartão (opcional)', { exact: true }).selectOption({ label: 'Meu cartão' })
  await salvar()
  await expect(area.locator('li')).toContainText('Vence em 05/11/2026')
  await expect(area.locator('li')).toContainText('Meu cartão')
  await area.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.getByLabel('Descrição', { exact: true }).fill('Mercado atualizado')
  await page.getByLabel('Valor (R$)').fill('100.00')
  await page.getByLabel('Vencimento (opcional)').fill('')
  await area.getByRole('button', { name: 'Salvar alterações' }).click()
  await expect(area.locator('li')).toContainText('Mercado atualizado')
  await expect(area.locator('li')).toContainText('Sem vencimento')

  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize().width)
  await page.screenshot({ path: testInfo.outputPath('financeiro.png'), fullPage: true })
  page.once('dialog', dialog => dialog.accept())
  await area.getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(area.getByText('Nenhum registro cadastrado.')).toBeVisible()
  await aba('Entradas')
  await expect(area.locator('li')).toContainText('Salário')
})
